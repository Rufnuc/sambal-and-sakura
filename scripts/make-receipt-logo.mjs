// Turns the logo into a 1-bit picture for the 80mm receipt printer (ESC/POS "GS v 0" raster) and writes
// src/server/receipt-logo.ts. Thermal printers only print black dots, so this is a print version of
// public/logo-mark.svg: black ring and petals on white instead of the dark disc. Run: node scripts/make-receipt-logo.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const SIZE = 192; // dots wide/high (the paper is 576 dots wide)
const petal = "M0 -26 C7 -20 7 -9 0 -4 C-7 -9 -7 -20 0 -26 Z";
const svg = `<svg width="128" height="128" viewBox="0 0 128 128" xmlns="http://www.w3.org/2000/svg">
  <rect width="128" height="128" fill="#fff"/>
  <circle cx="64" cy="64" r="60" fill="none" stroke="#000" stroke-width="2.5"/>
  <path d="M96 30 A46 46 0 1 0 103 74" stroke="#000" stroke-width="8" stroke-linecap="round" fill="none"/>
  <g transform="translate(64 66)" fill="#000">
    ${[0, 72, 144, 216, 288].map((r) => `<path d="${petal}" transform="rotate(${r})"/>`).join("")}
    <circle r="7" fill="#fff"/><circle r="3.2" fill="#000"/>
  </g>
</svg>`;

const { data, info } = await sharp(Buffer.from(svg)).resize(SIZE, SIZE).greyscale().raw().toBuffer({ resolveWithObject: true });
const bytesPerRow = Math.ceil(info.width / 8);
const bits = Buffer.alloc(bytesPerRow * info.height);
for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
  if (data[y * info.width + x] < 128) bits[y * bytesPerRow + (x >> 3)] |= 0x80 >> (x & 7);
}
writeFileSync("src/server/receipt-logo.ts",
  `// Generated by scripts/make-receipt-logo.mjs - do not edit by hand.\n` +
  `// The logo as a ${info.width}x${info.height} 1-bit picture for the receipt printer (1 = black dot, rows top to bottom).\n` +
  `export const RECEIPT_LOGO = { width: ${info.width}, height: ${info.height}, bits: "${bits.toString("base64")}" };\n`);
await sharp(Buffer.from(svg)).resize(SIZE, SIZE).threshold(128).png().toFile(process.argv[2] ?? "/dev/null");
console.log(`receipt logo: ${info.width}x${info.height}, ${bits.length} bytes`);
